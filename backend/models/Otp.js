const mongoose = require('mongoose');

const otpSchema = new mongoose.Schema({
  email: {
    type: String,
    required: true,
    lowercase: true,
    trim: true,
    index: true,
  },
  otp: {
    type: String,
    required: true,
  },
  purpose: {
    type: String,
    enum: ['LOGIN', 'REGISTER', 'RESET_PASSWORD'],
    default: 'LOGIN',
  },
  attempts: {
    type: Number,
    default: 0,
  },
  expiresAt: {
    type: Date,
    required: true,
    index: { expires: 0 }, // Document will automatically be deleted by MongoDB after expiresAt
  },
}, { timestamps: true });

module.exports = mongoose.model('Otp', otpSchema);

